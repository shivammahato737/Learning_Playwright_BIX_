//switch statement - It is used when we have multiple option

let department  = "cardiology"
switch(department){

    case "cardiology":
        console.log("heart specialist")
        break
        

    case "Neurology":
        console.log("Brain specialist")
        break
        
    case "orthopaedics":
        console.log("Bone specialist")
        break
        

    default:
        console.log("General consultation")
        
}